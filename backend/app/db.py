"""SQLite by default. Postgres when DATABASE_URL or POSTGRES_URL is set."""
import json
import logging
import os
import re
import sqlite3
import threading
from contextlib import contextmanager
from decimal import Decimal

from .config import Config

log = logging.getLogger("eip.db")
_lock = threading.Lock()
_pg_local = threading.local()
MIGRATIONS_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "migrations")
_ID_TABLES = {"users", "documents", "chunks", "jobs", "conversations", "messages", "llm_calls",
              "activity_logs", "agent_runs"}


def database_url() -> str:
    return (os.getenv("DATABASE_URL") or os.getenv("POSTGRES_URL") or "").strip()


def using_postgres() -> bool:
    return bool(database_url())


def _prepare(sql: str, want_id: bool = False):
    """Turn the app's SQLite statements into Postgres statements."""
    original = sql
    # Keep timestamps as text so the same comparisons work on both databases.
    stamp = "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')"
    s = sql.replace("datetime('now')", stamp).replace('datetime("now")', stamp)
    s = s.replace("date('now')", "(CURRENT_DATE)::text").replace('date("now")', "(CURRENT_DATE)::text")
    s = s.replace("date(created_at)", "substr(created_at, 1, 10)")
    ignore = re.search(r"INSERT\s+OR\s+IGNORE", original, re.I) is not None
    replace = re.search(r"INSERT\s+OR\s+REPLACE", original, re.I) is not None
    s = re.sub(r"\bINSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\b", "INSERT INTO", s, flags=re.I)
    s = s.replace("?", "%s")
    # window is reserved in Postgres and is a column on rate_limits.
    s = re.sub(r"\bwindow\b", '"window"', s, flags=re.I)
    s = re.sub(
        r"DO\s+UPDATE\s+SET\s+count\s*=\s*count\s*\+\s*excluded\.count",
        'DO UPDATE SET "count" = rate_limits."count" + EXCLUDED."count"',
        s,
        flags=re.I,
    )
    if ignore and "ON CONFLICT" not in s.upper():
        s += " ON CONFLICT DO NOTHING"
    elif replace and "ON CONFLICT" not in s.upper():
        s += " ON CONFLICT (cache_key) DO UPDATE SET response = EXCLUDED.response"
    returning = False
    if want_id and "RETURNING" not in s.upper():
        match = re.match(r"\s*INSERT\s+INTO\s+(\w+)", s, re.I)
        if match and match.group(1).lower() in _ID_TABLES:
            s += " RETURNING id"
            returning = True
    return s, returning


def _pg_migration_sql(sql: str) -> str:
    lines = [ln for ln in sql.splitlines() if not ln.strip().upper().startswith("PRAGMA")]
    text = "\n".join(lines)
    text = text.replace("INTEGER PRIMARY KEY AUTOINCREMENT",
                        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    text = re.sub(r"\bBLOB\b", "BYTEA", text)
    return text


class _Result:
    def __init__(self, rows, lastrowid=None):
        self._rows = rows or []
        self.lastrowid = lastrowid

    def fetchall(self):
        return self._rows

    def fetchone(self):
        return self._rows[0] if self._rows else None


class _PgConn:
    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql, params=(), want_id=False):
        import psycopg
        statement, returning = _prepare(sql, want_id=want_id)
        try:
            cur = self._conn.execute(statement, params or ())
        except (psycopg.OperationalError, psycopg.InterfaceError):
            _reset_postgres()
            self._conn = _connect_postgres()._conn
            cur = self._conn.execute(statement, params or ())
        except psycopg.Error:
            raise
        if not cur.description:
            return _Result([])
        rows = cur.fetchall()
        lastrowid = rows[0]["id"] if returning and rows else None
        return _Result([] if returning else rows, lastrowid)

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()


def _connect_sqlite():
    os.makedirs(os.path.dirname(os.path.abspath(Config.DATABASE_PATH)) or ".", exist_ok=True)
    conn = sqlite3.connect(Config.DATABASE_PATH, timeout=30, check_same_thread=False)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    conn.execute("PRAGMA journal_mode = WAL")
    return conn


def _connect_postgres():
    import psycopg
    from psycopg.rows import dict_row
    # One connection per thread. Opening a new Neon connection for every query
    # stalls the app once the free database has gone to sleep.
    raw = getattr(_pg_local, "raw", None)
    if raw is None or raw.closed:
        raw = psycopg.connect(database_url(), row_factory=dict_row, connect_timeout=15,
                              prepare_threshold=None)
        _pg_local.raw = raw
    return _PgConn(raw)


def _reset_postgres():
    raw = getattr(_pg_local, "raw", None)
    _pg_local.raw = None
    if raw is not None and not raw.closed:
        try:
            raw.close()
        except Exception:
            pass


def _connect():
    return _connect_postgres() if using_postgres() else _connect_sqlite()


@contextmanager
def get_conn():
    conn = _connect()
    try:
        yield conn
        conn.commit()
    except Exception:
        try:
            conn.rollback()
        except Exception:
            if using_postgres():
                _reset_postgres()
        raise
    finally:
        if not using_postgres():
            conn.close()


def _duplicate_column(exc: Exception) -> bool:
    text = str(exc).lower()
    return "duplicate column" in text or "already exists" in text


def _apply(conn, name: str, sql: str):
    if using_postgres():
        sql = _pg_migration_sql(sql)
        statements = [s.strip() for s in sql.split(";") if s.strip()]

        def _run(stmt: str):
            conn.execute("SAVEPOINT eip_stmt")
            try:
                conn.execute(stmt)
                conn.execute("RELEASE SAVEPOINT eip_stmt")
            except Exception as exc:
                conn.execute("ROLLBACK TO SAVEPOINT eip_stmt")
                if not _duplicate_column(exc):
                    raise

        for stmt in statements:
            _run(stmt)
        conn.execute("INSERT INTO schema_migrations (name) VALUES (?)", (name,))
    else:
        try:
            conn.executescript(sql)
        except sqlite3.OperationalError as e:
            if not _duplicate_column(e):
                raise
            for stmt in [s.strip() for s in sql.split(";") if s.strip()]:
                try:
                    conn.execute(stmt)
                except sqlite3.OperationalError as e2:
                    if not _duplicate_column(e2):
                        raise
        conn.execute("INSERT INTO schema_migrations (name) VALUES (?)", (name,))
    log.info("Applied migration %s", name)


def init_db() -> None:
    with _lock, get_conn() as conn:
        conn.execute("CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, "
                     "applied_at TEXT NOT NULL DEFAULT (datetime('now')))")
        done = {r["name"] for r in conn.execute("SELECT name FROM schema_migrations").fetchall()}
        for name in sorted(os.listdir(MIGRATIONS_DIR)):
            if name.endswith(".sql") and name not in done:
                with open(os.path.join(MIGRATIONS_DIR, name), encoding="utf-8") as f:
                    _apply(conn, name, f.read())


def _plain(value):
    """Postgres numeric results are Decimal, which Flask cannot serialize."""
    if isinstance(value, Decimal):
        return int(value) if value == value.to_integral_value() else float(value)
    if isinstance(value, memoryview):
        return bytes(value)
    return value


def _rows(result):
    return [{k: _plain(v) for k, v in dict(r).items()} for r in result.fetchall()]


def query(sql: str, params: tuple = (), one: bool = False):
    with get_conn() as conn:
        rows = _rows(conn.execute(sql, params))
    return (rows[0] if rows else None) if one else rows


def execute(sql: str, params: tuple = ()) -> int:
    try:
        with get_conn() as conn:
            if using_postgres():
                return conn.execute(sql, params, want_id=True).lastrowid
            return conn.execute(sql, params).lastrowid
    except Exception as exc:
        if using_postgres():
            import psycopg
            if isinstance(exc, psycopg.IntegrityError):
                raise sqlite3.IntegrityError(str(exc)) from exc
        raise


def log_activity(user_id, action: str, detail=None, level: str = "info") -> None:
    try:
        if detail is not None and not isinstance(detail, str):
            detail = json.dumps(detail, default=str)[:4000]
        execute("INSERT INTO activity_logs (user_id, level, action, detail) VALUES (?,?,?,?)",
                (user_id, level, action, detail))
    except Exception:
        pass
